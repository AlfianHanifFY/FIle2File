import Foundation

public struct SQLGenerator {
    public struct GenerationResult {
        public let sql: String
        public let totalBatches: Int
        public let totalRowsProcessed: Int
    }

    public static func generateSQL(
        tableName: String,
        mappings: [ColumnMapping],
        rows: [[String: String]],
        options: GeneratorOptions,
        ddlText: String? = nil
    ) -> GenerationResult {
        let activeMappings = mappings.filter { !$0.excelHeader.isEmpty }

        guard !activeMappings.isEmpty && !rows.isEmpty else {
            return GenerationResult(sql: "-- No columns mapped or empty data", totalBatches: 0, totalRowsProcessed: 0)
        }

        let columnsList = activeMappings.map { "\"\($0.sqlColumn)\"" }.joined(separator: ", ")
        let batchSize = max(1, options.batchSize)
        var sqlLines: [String] = []

        let formatter = ISO8601DateFormatter()
        sqlLines.append("-- Generated by File2File (Xlsx2SQL Module)")
        if let description = options.customDescription, !description.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            for line in description.components(separatedBy: .newlines) {
                sqlLines.append("-- Description: \(line)")
            }
        }
        sqlLines.append("-- Table: \(tableName)")
        sqlLines.append("-- Total Rows: \(rows.count)")
        sqlLines.append("-- Generated At: \(formatter.string(from: Date()))")
        sqlLines.append("")

        if let before = options.beforeProcess?.trimmingCharacters(in: .whitespacesAndNewlines), !before.isEmpty {
            sqlLines.append("-- Before Process")
            sqlLines.append(before)
            sqlLines.append("")
        }

        if options.includeCreateTable {
            sqlLines.append("-- Table Definition")
            let ddlStatement = resolveCreateTableDDL(tableName: tableName, mappings: activeMappings, ddlText: ddlText)
            sqlLines.append(ddlStatement)
            sqlLines.append("")
        }

        if options.useCopyFormat {
            sqlLines.append("COPY \"\(tableName)\" (\(columnsList)) FROM STDIN WITH (FORMAT text, NULL '\\N');")
            for row in rows {
                let copyRow = activeMappings
                    .map { m in formatCopyValue(m.isCustomValue ? m.customValue : row[m.excelHeader], mapping: m, row: row) }
                    .joined(separator: "\t")
                sqlLines.append(copyRow)
            }
            sqlLines.append("\\.")
            sqlLines.append("")

            if let after = options.afterProcess?.trimmingCharacters(in: .whitespacesAndNewlines), !after.isEmpty {
                sqlLines.append("-- After Process")
                sqlLines.append(after)
                sqlLines.append("")
            }

            return GenerationResult(sql: sqlLines.joined(separator: "\n"), totalBatches: 1, totalRowsProcessed: rows.count)
        }

        var batchCount = 0
        var i = 0
        while i < rows.count {
            batchCount += 1
            let end = min(i + batchSize, rows.count)
            let chunk = Array(rows[i..<end])
            
            sqlLines.append("-- Batch #\(batchCount) (\(chunk.count) rows)")
            sqlLines.append("INSERT INTO \"\(tableName)\" (\(columnsList)) VALUES")

            let valuesBlock = chunk.map { row in
                let vals = activeMappings
                    .map { m in formatSqlValue(m.isCustomValue ? m.customValue : row[m.excelHeader], mapping: m, row: row) }
                    .joined(separator: ", ")
                return "  (\(vals))"
            }.joined(separator: ",\n")

            sqlLines.append(valuesBlock)
            if options.onConflictDoNothing {
                sqlLines.append("ON CONFLICT DO NOTHING;")
            } else {
                sqlLines.append(";")
            }
            sqlLines.append("")
            
            i += batchSize
        }

        if let after = options.afterProcess?.trimmingCharacters(in: .whitespacesAndNewlines), !after.isEmpty {
            sqlLines.append("-- After Process")
            sqlLines.append(after)
            sqlLines.append("")
        }

        return GenerationResult(sql: sqlLines.joined(separator: "\n"), totalBatches: batchCount, totalRowsProcessed: rows.count)
    }

    public static func exportSQLToFile(
        tableName: String,
        mappings: [ColumnMapping],
        fileData: FileData,
        options: GeneratorOptions,
        outputURL: URL,
        ddlText: String? = nil,
        progress: ((_ processedRows: Int, _ totalRows: Int) -> Void)? = nil
    ) throws -> GenerationResult {
        let activeMappings = mappings.filter { !$0.excelHeader.isEmpty }
        guard !activeMappings.isEmpty else {
            throw NSError(domain: "SQLGenerator", code: 1, userInfo: [NSLocalizedDescriptionKey: "No columns mapped"])
        }

        FileManager.default.createFile(atPath: outputURL.path, contents: nil)
        guard let fileHandle = try? FileHandle(forWritingTo: outputURL) else {
            throw NSError(domain: "SQLGenerator", code: 2, userInfo: [NSLocalizedDescriptionKey: "Could not create file handle at \(outputURL.path)"])
        }
        defer { try? fileHandle.close() }

        var writeBuffer = Data()
        writeBuffer.reserveCapacity(65536)

        func writeString(_ string: String) {
            if let data = string.data(using: .utf8) {
                writeBuffer.append(data)
                if writeBuffer.count >= 65536 {
                    fileHandle.write(writeBuffer)
                    writeBuffer.removeAll(keepingCapacity: true)
                }
            }
        }

        func flushBuffer() {
            if !writeBuffer.isEmpty {
                fileHandle.write(writeBuffer)
                writeBuffer.removeAll()
            }
        }

        let columnsList = activeMappings.map { "\"\($0.sqlColumn)\"" }.joined(separator: ", ")
        let formatter = ISO8601DateFormatter()

        var headerLines = [
            "-- Generated by File2File (Xlsx2SQL Module)",
            "-- Table: \(tableName)",
            "-- Total Rows: \(fileData.totalRows)",
            "-- Generated At: \(formatter.string(from: Date()))",
            ""
        ]
        if let description = options.customDescription, !description.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            for line in description.components(separatedBy: .newlines) {
                headerLines.insert("-- Description: \(line)", at: 1)
            }
        }
        writeString(headerLines.joined(separator: "\n") + "\n")

        if let before = options.beforeProcess?.trimmingCharacters(in: .whitespacesAndNewlines), !before.isEmpty {
            var beforeBlock = "-- Before Process\n"
            beforeBlock += before
            beforeBlock += "\n\n"
            writeString(beforeBlock)
        }

        if options.includeCreateTable {
            var ddlBlock = "-- Table Definition\n"
            ddlBlock += resolveCreateTableDDL(tableName: tableName, mappings: activeMappings, ddlText: ddlText)
            ddlBlock += "\n\n"
            writeString(ddlBlock)
        }

        var totalRowsProcessed = 0
        var totalBatches = 0

        if options.useCopyFormat {
            writeString("COPY \"\(tableName)\" (\(columnsList)) FROM STDIN WITH (FORMAT text, NULL '\\N');\n")

            try FileParser.streamBatches(from: fileData, batchSize: max(1000, options.batchSize)) { chunk, _ in
                var chunkLines: [String] = []
                chunkLines.reserveCapacity(chunk.count)
                for row in chunk {
                    let copyRow = activeMappings
                        .map { m in formatCopyValue(m.isCustomValue ? m.customValue : row[m.excelHeader], mapping: m, row: row) }
                        .joined(separator: "\t")
                    chunkLines.append(copyRow)
                }
                writeString(chunkLines.joined(separator: "\n") + "\n")
                totalRowsProcessed += chunk.count
                totalBatches = 1
                progress?(totalRowsProcessed, fileData.totalRows)
            }

            writeString("\\.\n\n")
        } else {
            let batchSize = max(1, options.batchSize)
            try FileParser.streamBatches(from: fileData, batchSize: batchSize) { chunk, batchIdx in
                totalBatches = batchIdx
                var block = "-- Batch #\(batchIdx) (\(chunk.count) rows)\n"
                block += "INSERT INTO \"\(tableName)\" (\(columnsList)) VALUES\n"

                let valuesBlock = chunk.map { row in
                    let vals = activeMappings
                        .map { m in formatSqlValue(m.isCustomValue ? m.customValue : row[m.excelHeader], mapping: m, row: row) }
                        .joined(separator: ", ")
                    return "  (\(vals))"
                }.joined(separator: ",\n")

                block += valuesBlock + "\n"
                if options.onConflictDoNothing {
                    block += "ON CONFLICT DO NOTHING;\n\n"
                } else {
                    block += ";\n\n"
                }
                writeString(block)

                totalRowsProcessed += chunk.count
                progress?(totalRowsProcessed, fileData.totalRows)
            }
        }

        if let after = options.afterProcess?.trimmingCharacters(in: .whitespacesAndNewlines), !after.isEmpty {
            var afterBlock = "-- After Process\n"
            afterBlock += after
            afterBlock += "\n\n"
            writeString(afterBlock)
        }

        flushBuffer()
        return GenerationResult(sql: "", totalBatches: totalBatches, totalRowsProcessed: totalRowsProcessed)
    }

    private static func formatSqlValue(_ rawVal: String?, mapping: ColumnMapping, row: [String: String]? = nil) -> String {
        guard let rawVal = rawVal else {
            return mapping.isCustomValue ? "NULL" : resolveNullOrEmpty(mapping: mapping)
        }
        var strVal = rawVal.trimmingCharacters(in: .whitespacesAndNewlines)

        if strVal.contains("${"), let row = row {
            strVal = resolveColumnVariables(template: strVal, row: row)
        }

        let nullStrings = ["", "null", "n/a", "none", "nan"]
        if nullStrings.contains(strVal.lowercased()) {
            return mapping.isCustomValue ? "NULL" : resolveNullOrEmpty(mapping: mapping)
        }

        let upper = strVal.uppercased()
        if upper == "DEFAULT" || upper == "NULL" {
            return upper
        }

        // Handle user-specified custom literal or raw SQL expression
        if mapping.isCustomValue {
            return strVal
        }

        let type = mapping.sqlType.uppercased()

        if type == "INTEGER" || type == "BIGINT" || type == "SMALLINT" {
            let cleanNum = strVal.replacingOccurrences(of: ",", with: "")
            if let parsedInt = Int64(cleanNum) {
                return String(parsedInt)
            }
            return mapping.isCustomValue ? (strVal.hasPrefix("'") ? strVal : "'\(escapeString(strVal))'") : resolveNullOrEmpty(mapping: mapping)
        }

        if type == "NUMERIC" || type == "DOUBLE PRECISION" || type == "REAL" {
            let cleanNum = strVal.replacingOccurrences(of: "[\\$,]", with: "", options: .regularExpression)
            if let parsedDouble = Double(cleanNum) {
                return String(parsedDouble)
            }
            return resolveNullOrEmpty(mapping: mapping)
        }

        if type == "BOOLEAN" {
            let lower = strVal.lowercased()
            if ["true", "t", "1", "yes", "y"].contains(lower) { return "TRUE" }
            if ["false", "f", "0", "no", "n"].contains(lower) { return "FALSE" }
            return resolveNullOrEmpty(mapping: mapping)
        }

        if type.contains("DATE") || type.contains("TIMESTAMP") {
            let lower = strVal.lowercased()
            if ["now()", "current_timestamp", "current_date"].contains(lower) {
                return strVal.uppercased()
            }
            if let dateStr = parseAndFormatDate(strVal, targetType: type) {
                return "'\(dateStr)'"
            }
            return resolveNullOrEmpty(mapping: mapping)
        }

        if type.contains("JSON") {
            let escaped = escapeString(strVal)
            return "'\(escaped)'::jsonb"
        }

        return "'\(escapeString(strVal))'"
    }

    private static func resolveNullOrEmpty(mapping: ColumnMapping) -> String {
        if mapping.nullHandling == .defaultValue && !mapping.defaultValue.isEmpty {
            var defaultMapping = mapping
            defaultMapping.nullHandling = .setNull
            return formatSqlValue(mapping.defaultValue, mapping: defaultMapping)
        }
        if mapping.nullHandling == .emptyString {
            let type = mapping.sqlType.uppercased()
            if type.contains("CHAR") || type.contains("TEXT") || type.contains("VARCHAR") {
                return "''"
            }
        }
        return "NULL"
    }

    private static func formatCopyValue(_ rawVal: String?, mapping: ColumnMapping, row: [String: String]? = nil) -> String {
        guard let rawVal = rawVal else {
            return resolveCopyNullOrEmpty(mapping: mapping)
        }
        var strVal = rawVal.trimmingCharacters(in: .whitespacesAndNewlines)
        if strVal.contains("${"), let row = row {
            strVal = resolveColumnVariables(template: strVal, row: row)
        }
        if strVal.isEmpty || strVal.lowercased() == "null" {
            return resolveCopyNullOrEmpty(mapping: mapping)
        }

        return strVal
            .replacingOccurrences(of: "\\", with: "\\\\")
            .replacingOccurrences(of: "\t", with: "\\t")
            .replacingOccurrences(of: "\n", with: "\\n")
            .replacingOccurrences(of: "\r", with: "\\r")
    }

    private static func resolveCopyNullOrEmpty(mapping: ColumnMapping) -> String {
        if mapping.nullHandling == .defaultValue && !mapping.defaultValue.isEmpty {
            return mapping.defaultValue
                .replacingOccurrences(of: "\\", with: "\\\\")
                .replacingOccurrences(of: "\t", with: "\\t")
                .replacingOccurrences(of: "\n", with: "\\n")
                .replacingOccurrences(of: "\r", with: "\\r")
        }
        if mapping.nullHandling == .emptyString {
            return ""
        }
        return "\\N"
    }

    private static func resolveCreateTableDDL(
        tableName: String,
        mappings: [ColumnMapping],
        ddlText: String?
    ) -> String {
        if let ddl = ddlText?.trimmingCharacters(in: .whitespacesAndNewlines), !ddl.isEmpty {
            var formatted = ddl
            formatted = formatted.replacingOccurrences(of: "[“”]", with: "\"", options: .regularExpression)
            formatted = formatted.replacingOccurrences(of: "[‘’]", with: "'", options: .regularExpression)

            if !formatted.localizedCaseInsensitiveContains("IF NOT EXISTS") {
                formatted = formatted.replacingOccurrences(
                    of: "(?i)CREATE\\s+TABLE\\s+",
                    with: "CREATE TABLE IF NOT EXISTS ",
                    options: .regularExpression
                )
            }
            if !formatted.trimmingCharacters(in: .whitespacesAndNewlines).hasSuffix(";") {
                formatted += ";"
            }
            return formatted
        } else {
            let colDefs = mappings.map { m in
                var def = "    \"\(m.sqlColumn)\" \(m.sqlType)"
                if !m.isNullable {
                    def += " NOT NULL"
                }
                return def
            }.joined(separator: ",\n")
            return "CREATE TABLE IF NOT EXISTS \"\(tableName)\" (\n\(colDefs)\n);"
        }
    }

    private static func escapeString(_ val: String) -> String {
        return val
            .replacingOccurrences(of: "'", with: "''")
            .replacingOccurrences(of: "\0", with: "")
    }

    private static func parseAndFormatDate(_ val: String, targetType: String) -> String? {
        if let serial = Double(val), serial > 1000 && serial < 100000 {
            let utcDays = floor(serial - 25569)
            let utcSeconds = utcDays * 86400
            let date = Date(timeIntervalSince1970: utcSeconds)

            let formatter = DateFormatter()
            formatter.timeZone = TimeZone(secondsFromGMT: 0)
            if targetType.contains("DATE") && !targetType.contains("TIME") {
                formatter.dateFormat = "yyyy-MM-dd"
            } else {
                formatter.dateFormat = "yyyy-MM-dd HH:mm:ss"
            }
            return formatter.string(from: date)
        }

        let dateFormats = [
            "yyyy-MM-dd'T'HH:mm:ssZ",
            "yyyy-MM-dd HH:mm:ss",
            "yyyy-MM-dd",
            "MM/dd/yyyy HH:mm:ss",
            "MM/dd/yyyy",
            "dd-MM-yyyy"
        ]

        let formatter = DateFormatter()
        for fmt in dateFormats {
            formatter.dateFormat = fmt
            if let date = formatter.date(from: val) {
                let outFormatter = DateFormatter()
                if targetType == "DATE" {
                    outFormatter.dateFormat = "yyyy-MM-dd"
                } else {
                    outFormatter.dateFormat = "yyyy-MM-dd HH:mm:ss"
                }
                return outFormatter.string(from: date)
            }
        }

        return nil
    }

    public static func resolveColumnVariables(template: String, row: [String: String]) -> String {
        var result = template
        let pattern = "\\$\\{([^\\}]+)\\}"
        guard let regex = try? NSRegularExpression(pattern: pattern, options: []) else {
            return template
        }
        let nsString = template as NSString
        let matches = regex.matches(in: template, options: [], range: NSRange(location: 0, length: nsString.length))

        for match in matches.reversed() {
            let varRange = match.range(at: 1)
            let fullRange = match.range(at: 0)
            let colName = nsString.substring(with: varRange).trimmingCharacters(in: .whitespacesAndNewlines)
            let replacement = row[colName] ?? ""
            result = (result as NSString).replacingCharacters(in: fullRange, with: replacement)
        }
        return result
    }
}
